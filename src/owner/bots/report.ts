const day = (iso: string | undefined) => iso?.slice(0, 10) ?? '-';

/** A count in the report's language; a tilde marks estimates from a sampling source. */
function amount(activity: BotActivity, language: Language, value: number): string {
  return `${activity.sampled ? '~' : ''}${Math.round(value).toLocaleString(language)}`;
}

function statuses(values: Readonly<Record<string, number>>): string {
  const entries = Object.entries(values).sort((a, b) => b[1] - a[1]).slice(0, 6);
  return entries.length === 0 ? '-' : entries.map(([status, hits]) => `${status} x${Math.round(hits)}`).join(', ');
}

function evidenceLine(item: EvidenceItem, language: Language): string {
  const where = [item.url, item.line ? format(ui(language).lineNumber, { line: item.line }) : undefined].filter(Boolean).join(', ');
  const head = `${cleanLine(evidenceLabelText(language, item))}${where ? ` (${untrustedInline(where, 160)})` : ''}`;
  if (item.excerpt === undefined) return head;
  return item.excerpt.includes('\n') ? `${head}:\n\n${untrustedBlock(item.excerpt, 3000).split('\n').map(line => `    ${line}`).join('\n')}\n` : `${head}: ${untrustedInline(item.excerpt, 300)}`;
}

function tallyCell(activity: BotActivity, language: Language, bot: BotSummary, value: number): string {
  return `${amount(activity, language, value)}${bot.truncated ? '+' : ''}`;
}

/** bots.md: what crawlers did, the rule findings and how the data was read. Untrusted text is quoted as data. */
export function renderBotsMarkdown(report: BotsReport, language: Language): string {
  const t = ui(language);
  const l = labels[language];
  const activity = report.activity;
  const evidence = new Map(report.evidence.map(item => [item.id, item]));
  const lines: string[] = [];
  const site = report.origin ? new URL(report.origin).host : undefined;
  lines.push(`# ${site ? format(l.title, { site: cleanLine(site, 120) }) : l.titleNoSite}`, '');
  lines.push(format(l.window, { start: day(activity.window.start), end: day(activity.window.end), days: activity.window.days }), '');
  lines.push(format(l.generated, { version: report.tool.version, date: day(report.generatedAt) }), '');
  lines.push(`## ${l.sources}`, '');
  for (const source of activity.sources) {
    if (source.kind === 'access-log') {
      lines.push(`- ${format(l.logSource, { file: untrustedInline(source.file, 120), format: source.format, lines: source.lines, records: source.records, malformed: source.malformed })}`);
    } else {
      lines.push(`- ${format(l.cloudflareSource, { zone: untrustedInline(source.zone, 120), queries: source.queries, dimensions: source.dimensions.map(name => `\`${cleanLine(name, 40)}\``).join(', ') })}`);
    }
  }
  if (activity.sampled) lines.push('', l.sampled);
  lines.push('', l.untrusted, '');

  lines.push(`## ${t.findings}`, '');
  const failures = report.findings.filter(finding => finding.outcome === 'fail')
    .sort((a, b) => severityWeights[b.severity ?? 'info'] - severityWeights[a.severity ?? 'info'] || a.ruleId.localeCompare(b.ruleId));
  if (failures.length === 0) lines.push(l.noFindings);
  for (const finding of failures) {
    const rule = catalogRule(finding.ruleId);
    const texts = rule ? ruleTexts(language, rule) : { title: finding.ruleId, why: '', fix: '' };
    lines.push(`- **[${t.severities[finding.severity ?? 'info']}] ${cleanLine(texts.title)}** (\`${finding.ruleId}\`)`);
    const text = findingMessage(language, finding.ruleId, 'fail', finding.reason, finding.params);
    if (text) lines.push(`  ${cleanLine(text, 600)}`);
    for (const id of finding.evidence.slice(0, 4)) {
      const item = evidence.get(id);
      if (item) lines.push(`  - ${t.evidence}: ${evidenceLine(item, language)}`);
    }
    if (texts.fix) lines.push(`  - ${t.fix}: ${cleanLine(texts.fix, 700)}`);
  }
  lines.push('');

  lines.push(`## ${l.crawlers}`, '');
  if (activity.bots.length === 0) {
    lines.push(l.noCrawlers, '');
  } else {
    lines.push(`| ${l.columns.join(' | ')} |`, `| ${l.columns.map(() => '---').join(' | ')} |`);
    for (const bot of activity.bots) {
      const counts = !bot.verifiable && bot.verified.hits === 0
        ? [`${l.unverifiable}: ${tallyCell(activity, language, bot, bot.unverified.hits)}`, '-', '-']
        : [tallyCell(activity, language, bot, bot.verified.hits), tallyCell(activity, language, bot, bot.unverified.hits), tallyCell(activity, language, bot, bot.spoofed.hits)];
      lines.push(`| ${bot.name} | ${bot.operator} | ${l.purposes[bot.purpose]} | ${counts.join(' | ')} | ${day(bot.verified.lastSeen)} | ${amount(activity, language, bot.robotsTxt)} | ${amount(activity, language, bot.llmsTxt)} |`);
    }
    if (activity.bots.some(bot => bot.truncated)) lines.push('', `+ ${l.lowerBound}`);
    lines.push('', `### ${l.answers}`, '', `| ${l.answerColumns.join(' | ')} |`, `| ${l.answerColumns.map(() => '---').join(' | ')} |`);
    for (const bot of activity.bots) {
      const tally = bot.basis === 'verified' ? bot.verified : bot.unverified;
      lines.push(`| ${bot.name} | ${statuses(tally.statuses)} | ${amount(activity, language, tally.challenges)} | ${amount(activity, language, bot.scripts)} | ${amount(activity, language, bot.stylesheets)} | ${amount(activity, language, tally.bytes)} |`);
    }
    const covered = activity.bots.filter(bot => bot.coverage && bot.basis === 'verified');
    if (covered.length > 0) {
      lines.push('', `### ${l.coverage}`, '', `| ${l.coverageColumns.join(' | ')} |`, `| ${l.coverageColumns.map(() => '---').join(' | ')} |`);
      for (const bot of covered) lines.push(`| ${bot.name} | ${bot.coverage!.fetched} / ${bot.coverage!.urls} | ${bot.coverage!.ok} / ${bot.coverage!.urls} |`);
    }
    lines.push('');
  }

  lines.push(`## ${l.notObservable}`, '');
  for (const token of activity.notObservable) lines.push(`- ${format(l.notObservableLine, { name: token.name, operator: token.operator })}`);
  lines.push('');

  lines.push(`## ${l.referrals}`, '');
  const referrals = activity.referrals;
  if (!referrals) lines.push(l.referralsMissing);
  else if (referrals.total === 0 && referrals.tagged === 0 && referrals.byHost.length === 0) lines.push(l.referralsNone);
  else {
    for (const entry of referrals.byHost) lines.push(`- ${format(l.referralLine, { host: entry.host, assistant: entry.assistant, visits: amount(activity, language, entry.visits) })}`);
    lines.push(`- ${format(l.tagged, { count: amount(activity, language, referrals.tagged) })}`);
  }
  lines.push('', l.referralsCaveat, '');

  lines.push(`## ${t.method}`, '', ...l.definitions.map(line => `- ${line}`), '');
  lines.push(format(l.clientIp, { source: `\`${activity.clientIp.source}\``, checkable: amount(activity, language, activity.clientIp.checkable), claims: amount(activity, language, activity.clientIp.claims) }));
  const discarded = Object.entries(activity.clientIp.discarded);
  if (discarded.length > 0) lines.push('', format(l.discarded, { list: discarded.map(([reason, hits]) => `\`${cleanLine(reason, 40)}\` ${amount(activity, language, hits)}`).join(', ') }));
  lines.push('', activity.dns.enabled ? format(activity.dns.capped ? l.dnsOnCapped : l.dnsOn, { lookups: activity.dns.lookups, errors: activity.dns.errors }) : l.dnsOff);
  if (activity.site?.robots) lines.push('', format(l.robots, { date: day(activity.site.robots.effectiveFrom), source: l.robotsSources[activity.site.robots.effectiveFromSource] }));
  if (activity.ipLists.length > 0) {
    lines.push('', `### ${l.lists}`, '');
    for (const list of activity.ipLists) {
      lines.push(`- ${format(l.listLine, { id: `\`${list.id}\``, prefixes: list.prefixes, created: untrustedInline(list.creationTime ?? '-', 40), from: l.listSources[list.from] })} <${list.url}>`);
    }
  }
  if (activity.warnings.length > 0) lines.push('', `### ${t.warnings}`, '', ...activity.warnings.map(warning => `- ${cleanLine(warning, 400)}`));
  lines.push('');
  return lines.join('\n');
}
