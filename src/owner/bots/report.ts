/** bots.json: the activity, the findings of the crawler rules and the evidence they cite. */
export interface BotsReport {
  readonly schemaVersion: 1;
  readonly tool: { readonly name: 'altimeter'; readonly version: string };
  readonly generatedAt: string;
  readonly origin?: string;
  readonly activity: BotActivity;
  readonly findings: readonly Finding[];
  readonly evidence: readonly EvidenceItem[];
}

/** Ids of the rules that read crawler activity. */
export const botRuleIds: readonly string[] = implementations.map(entry => entry.id);

/** Evaluates the crawler rules over the activity and the site's robots.txt and sitemaps. */
export function buildBotsReport(activity: BotActivity, site: SiteFacts | undefined): BotsReport {
  const facts: SiteFacts = {
    ...(site ?? { origin: activity.site?.origin ?? 'https://unknown.invalid', sitemaps: [], variants: [], siblings: [], pages: new Map(), crawled: false, agentProbes: [], resources: [], localeProbes: [] }),
    owner: { ...site?.owner, bots: activity },
  };
  const evidence = new EvidenceStore();
  const findings = site
    ? runRules({ rules: catalogRules.filter(entry => botRuleIds.includes(entry.id)), implementations: new Map(implementations.map(entry => [entry.id, entry])), site: facts, evidence })
    : runRules({
      rules: catalogRules.filter(entry => botRuleIds.includes(entry.id) && !entry.inputs.some(input => input === 'robots' || input === 'sitemaps')),
      implementations: new Map(implementations.map(entry => [entry.id, entry])), site: facts, evidence,
    });
  return {
    schemaVersion: 1, tool: { name: 'altimeter', version }, generatedAt: activity.fetchedAt,
    ...(activity.site?.origin ? { origin: activity.site.origin } : {}), activity, findings, evidence: evidence.all(),
  };
}

