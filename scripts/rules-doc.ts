import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { myths, rules } from '../src/catalog/index.ts';
import { categories } from '../src/core/types.ts';
import { ui } from '../src/i18n/ui.ts';

const target = fileURLToPath(new URL('../docs/rules.md', import.meta.url));
const readme = fileURLToPath(new URL('../README.md', import.meta.url));
const badgePattern = /\[!\[Rules\]\(https:\/\/img\.shields\.io\/badge\/rules-\d+%20with%20primary%20sources-2b4c7e\)\]\(docs\/rules\.md\)/u;

/** The README badge with the number of rules that run: those in this version and those that read owner data. */
export function rulesBadge(): string {
  const count = rules.filter(rule => rule.status !== 'planned').length;
  return `[![Rules](https://img.shields.io/badge/rules-${count}%20with%20primary%20sources-2b4c7e)](docs/rules.md)`;
}

function cell(value: string): string {
  return value.replace(/\|/gu, '\\|').replace(/\s+/gu, ' ').trim();
}

/** The catalog as a Markdown reference, generated so it never drifts from the data. */
export function renderRulesDoc(): string {
  const names = ui('en').categories;
  const lines = [
    '# Rule catalog',
    '',
    '<!-- Generated by `npm run docs:rules` from src/catalog. Do not edit by hand. -->',
    '',
    `${rules.length} rules and ${myths.length} documented myths. Every rule cites at least one primary source and the date it was last verified.`,
    'Status `v1` rules run in this version; `planned` rules need an input this version does not collect; `requires-owner-data` rules need Search Console, Bing Webmaster Tools or server logs.',
    '',
  ];
  for (const category of categories) {
    const entries = rules.filter(rule => rule.category === category);
    lines.push(`## ${names[category]}`, '', '| Rule | Check | Max severity | Method | Status | Sources |', '| --- | --- | --- | --- | --- | --- |');
    for (const rule of entries) {
      const sources = rule.sources.map(source => `[${new URL(source.url).hostname}](${source.url}) (${source.verified})`).join('<br>');
      lines.push(`| \`${rule.id}\` | ${cell(rule.title)} | ${rule.maxSeverity} | ${rule.method} | ${rule.status} | ${sources} |`);
    }
    lines.push('');
  }
  lines.push('## Myths', '', 'Claims that current guidance contradicts. Altimeter never reports them as problems and rejects analyst output that repeats them.', '');
  for (const myth of myths) lines.push(`- **${cell(myth.claim)}** ${cell(myth.reality)} ([source](${myth.sources[0]!.url}))`);
  lines.push('');
  return lines.join('\n');
}

export async function rulesDocInSync(): Promise<boolean> {
  try {
    return (await readFile(target, 'utf8')) === renderRulesDoc() && (await readFile(readme, 'utf8')).includes(rulesBadge());
  } catch {
    return false;
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await writeFile(target, renderRulesDoc(), 'utf8');
  const text = await readFile(readme, 'utf8');
  if (!badgePattern.test(text)) throw new Error('README.md has no rules badge to update.');
  await writeFile(readme, text.replace(badgePattern, rulesBadge()), 'utf8');
  process.stdout.write(`Wrote docs/rules.md (${rules.length} rules, ${myths.length} myths) and the README badge\n`);
}
